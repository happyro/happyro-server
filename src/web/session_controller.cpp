#include "session_controller.hpp"

#include <nlohmann/json.hpp>
#include <common/sql.hpp>
#include "sqllock.hpp"
#include "web.hpp"

namespace {
using Json = nlohmann::json;
void reply(Response& res, int status, const Json& value = Json::object()) {
	res.status = status;
	res.set_header("Cache-Control", "no-store");
	res.set_content(value.dump(), "application/json");
}
bool hex(const Json& body, const char* key, size_t min = 64, size_t max = 64) {
	if (!body.contains(key) || !body[key].is_string()) return false;
	const auto& s = body[key].get_ref<const std::string&>();
	return s.size() >= min && s.size() <= max && s.find_first_not_of("0123456789abcdefABCDEF") == std::string::npos;
}
bool parse(const Request& req, Response& res, Json& body) {
	if (req.body.size() > 4096) { reply(res, 400); return false; }
	body = Json::parse(req.body, nullptr, false);
	if (!body.is_object()) { reply(res, 400); return false; }
	return true;
}
void describe(Sql* sql, const std::string& token, Response& res) {
	if (SQL_SUCCESS != Sql_Query(sql,
		"SELECT s.account_id,a.userid,s.persistent,s.expires FROM happyro_sessions s "
		"JOIN `%s` a ON a.account_id=s.account_id WHERE s.token_hash=SHA2('%s',256)", login_table, token.c_str()) ||
		SQL_SUCCESS != Sql_NextRow(sql)) { reply(res, 503); return; }
	char *aid, *username, *persistent, *expires;
	Sql_GetData(sql, 0, &aid, nullptr); Sql_GetData(sql, 1, &username, nullptr);
	Sql_GetData(sql, 2, &persistent, nullptr); Sql_GetData(sql, 3, &expires, nullptr);
	const Json result = {{"accountId", std::stoul(aid)}, {"username", username},
		{"persistent", std::string(persistent) == "1"}, {"expires", std::stoll(expires)}};
	Sql_FreeResult(sql);
	reply(res, 200, result);
}
}

HANDLER_FUNC(session_create) {
	Json body;
	if (!parse(req, res, body)) return;
	if (!hex(body, "nextToken") || !hex(body, "webToken", 1, 64) ||
		!body.contains("accountId") || !body["accountId"].is_number_unsigned() ||
		body["accountId"].get<uint64_t>() > UINT32_MAX ||
		!body.contains("persistent") || !body["persistent"].is_boolean()) { reply(res, 400); return; }
	SQLLock lock(LOGIN_SQL_LOCK); lock.lock(); auto* sql = lock.getHandle();
	// Generated by Gateway's OS CSPRNG; only its SHA-256 digest is retained.
	const std::string token = body["nextToken"], web_token = body["webToken"];
	const uint32_t aid = body["accountId"];
	Sql_Query(sql, "DELETE FROM happyro_sessions WHERE expires<=UNIX_TIMESTAMP()");
	if (SQL_SUCCESS != Sql_Query(sql,
		"INSERT INTO happyro_sessions(token_hash,account_id,password_hash,persistent,expires) "
		"SELECT SHA2('%s',256),account_id,SHA2(user_pass,256),%d,UNIX_TIMESTAMP()+2592000 "
		"FROM `%s` WHERE account_id='%u' AND web_auth_token='%s' AND web_auth_token_enabled=1 "
		"AND state=0 AND sex<>'S' AND unban_time<=UNIX_TIMESTAMP() "
		"AND (expiration_time=0 OR expiration_time>UNIX_TIMESTAMP())",
		token.c_str(), body["persistent"].get<bool>() ? 1 : 0, login_table, aid, web_token.c_str())) { reply(res, 503); return; }
	if (Sql_NumRowsAffected(sql) != 1) { reply(res, 401); return; }
	if (hex(body, "previousToken")) {
		const std::string previous = body["previousToken"];
		Sql_Query(sql, "DELETE FROM happyro_sessions WHERE token_hash=SHA2('%s',256)", previous.c_str());
	}
	describe(sql, token, res);
}

HANDLER_FUNC(session_resume) {
	Json body;
	if (!parse(req, res, body)) return;
	if (!hex(body, "token") || !hex(body, "nextToken") || !hex(body, "ticket")) { reply(res, 400); return; }
	const std::string token = body["token"], next = body["nextToken"], ticket = body["ticket"];
	SQLLock lock(LOGIN_SQL_LOCK); lock.lock(); auto* sql = lock.getHandle();
	if (SQL_SUCCESS != Sql_Query(sql,
		"UPDATE happyro_sessions s JOIN `%s` a ON a.account_id=s.account_id "
		"SET s.token_hash=SHA2('%s',256),s.ticket_hash=SHA2('%s',256),s.ticket_expires=UNIX_TIMESTAMP()+30 "
		"WHERE s.token_hash=SHA2('%s',256) AND s.expires>UNIX_TIMESTAMP() "
		"AND s.password_hash=SHA2(a.user_pass,256) AND a.state=0 AND a.sex<>'S' "
		"AND a.unban_time<=UNIX_TIMESTAMP() AND (a.expiration_time=0 OR a.expiration_time>UNIX_TIMESTAMP())",
		login_table, next.c_str(), ticket.c_str(), token.c_str())) { reply(res, 503); return; }
	if (Sql_NumRowsAffected(sql) != 1) { reply(res, 401); return; }
	describe(sql, next, res);
}

HANDLER_FUNC(session_revoke) {
	Json body;
	if (!parse(req, res, body)) return;
	if (!hex(body, "token")) { reply(res, 400); return; }
	const std::string token = body["token"];
	SQLLock lock(LOGIN_SQL_LOCK); lock.lock(); auto* sql = lock.getHandle();
	if (SQL_SUCCESS != Sql_Query(sql, "DELETE FROM happyro_sessions WHERE token_hash=SHA2('%s',256)", token.c_str())) {
		reply(res, 503); return;
	}
	reply(res, 200);
}
